export interface MakeRealRequest {
	shapes?: any[]
	svg?: string
	context?: string
}

export interface MakeRealResponse {
	ok: boolean
	html: string
	source: 'llm' | 'fallback'
	error?: string
}

export function generateFallbackHtml(shapes: any[] = [], context = ''): string {
	const shapeElements: string[] = []

	for (const s of shapes) {
		const props = s.props || {}
		const text = props.text || props.title || props.label || ''

		if (s.type === 'wired-button') {
			shapeElements.push(`
        <button class="px-5 py-2.5 rounded-lg font-medium text-white shadow-sm transition hover:opacity-90 active:scale-95" style="background-color: ${props.color || '#3b82f6'};">
          ${text || 'Button'}
        </button>`)
		} else if (s.type === 'wired-input') {
			shapeElements.push(`
        <div class="flex flex-col gap-1 w-full max-w-sm">
          <label class="text-xs font-semibold text-slate-500 uppercase tracking-wider">${props.placeholder || 'Input Field'}</label>
          <input type="text" placeholder="${props.placeholder || 'Enter value...'}" class="px-3.5 py-2 border border-slate-300 rounded-lg text-sm focus:outline-none focus:ring-2 focus:ring-blue-500" />
        </div>`)
		} else if (s.type === 'wired-toggle') {
			shapeElements.push(`
        <label class="inline-flex items-center gap-3 cursor-pointer">
          <div class="relative inline-flex items-center h-6 rounded-full w-11 bg-blue-600">
            <span class="inline-block w-4 h-4 transform translate-x-6 bg-white rounded-full transition"></span>
          </div>
          <span class="text-sm font-medium text-slate-700">Toggle Switch</span>
        </label>`)
		} else if (s.type === 'wired-card') {
			shapeElements.push(`
        <div class="p-6 bg-white border border-slate-200 rounded-xl shadow-sm hover:shadow-md transition">
          <h3 class="text-lg font-bold text-slate-900 mb-2">${props.title || 'Card Title'}</h3>
          <p class="text-sm text-slate-600">Interactive wireframe component generated by Sonagi Draw Make Real.</p>
        </div>`)
		} else if (s.type === 'note') {
			shapeElements.push(`
        <div class="p-5 bg-amber-100 border border-amber-300 rounded-lg shadow-sm text-amber-950 font-sans text-sm rotate-[-1deg]">
          <p class="font-medium">${text || 'Sticky Note Note'}</p>
        </div>`)
		} else {
			shapeElements.push(`
        <div class="p-4 bg-slate-50 border border-slate-200 rounded-lg text-slate-800 text-sm">
          ${text || s.type}
        </div>`)
		}
	}

	return `<!DOCTYPE html>
<html lang="ko">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Make Real Live Preview</title>
  <script src="https://cdn.tailwindcss.com"></script>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Pretendard, sans-serif; }
  </style>
</head>
<body class="bg-slate-50 min-h-screen flex items-center justify-center p-6">
  <div class="w-full max-w-2xl bg-white rounded-2xl shadow-xl border border-slate-200/80 p-8 space-y-6">
    <div class="border-b border-slate-100 pb-4">
      <span class="text-xs font-mono font-semibold px-2.5 py-1 rounded-full bg-blue-50 text-blue-600">MAKE REAL • SONAGI</span>
      <h1 class="text-xl font-bold text-slate-900 mt-2">${context || 'Interactive Prototype'}</h1>
    </div>
    <div class="flex flex-wrap gap-4 items-center justify-start">
      ${shapeElements.length > 0 ? shapeElements.join('\n') : '<p class="text-slate-400">No components provided.</p>'}
    </div>
  </div>
</body>
</html>`
}

export async function executeMakeReal(req: MakeRealRequest): Promise<MakeRealResponse> {
	const { shapes = [], svg = '', context = '' } = req

	const apiBase = process.env.OPENAI_API_BASE || process.env.AI_API_BASE || 'http://127.0.0.1:38107/v1'
	const apiKey = process.env.OPENAI_API_KEY || process.env.AI_API_KEY || 'dummy'
	const model = process.env.MAKE_REAL_MODEL || 'gemini-3.5-flash-lite'

	const shapesSummary = shapes
		.map((s) => {
			const text = s.props?.text || s.props?.title || s.props?.label || ''
			return `- Type: ${s.type}, Pos: (${Math.round(s.x)}, ${Math.round(s.y)}), Text/Title: "${text}"`
		})
		.join('\n')

	const systemPrompt = `You are an expert modern web designer and frontend engineer.
Your task is to take the user's wireframe drawing layout and generate a gorgeous, self-contained, fully interactive Single File HTML + Tailwind CSS web prototype.

Requirements:
1. Include <script src="https://cdn.tailwindcss.com"></script> in <head>.
2. Use modern, beautiful design tokens (clean typography, subtle borders, soft shadows, rounded corners, good contrast).
3. Make all buttons, inputs, toggles, and modals fully interactive using vanilla JavaScript inside <script> tags.
4. If there is a form, handle submit with a friendly toast or alert.
5. If there is a modal or drawer, make open/close work smoothly.
6. Return ONLY the raw HTML string starting with <!DOCTYPE html> and ending with </html>. Do NOT wrap in markdown codeblocks.`

	const userPrompt = `Wireframe Components Layout:
${shapesSummary || 'Generic UI prototype'}

Context & Notes:
${context || 'Convert this wireframe into a responsive, clean, high-fidelity UI page'}

${svg ? `Visual SVG Outline:\n${svg.slice(0, 1500)}` : ''}`

	const controller = new AbortController()
	const timeout = setTimeout(() => controller.abort(), 6000)

	try {
		const response = await fetch(`${apiBase.replace(/\/$/, '')}/chat/completions`, {
			method: 'POST',
			headers: {
				'Content-Type': 'application/json',
				'Authorization': `Bearer ${apiKey}`
			},
			body: JSON.stringify({
				model,
				messages: [
					{ role: 'system', content: systemPrompt },
					{ role: 'user', content: userPrompt }
				],
				temperature: 0.3,
				max_tokens: 1500
			}),
			signal: controller.signal
		})

		clearTimeout(timeout)

		if (!response.ok) {
			console.warn(`[Make Real] Upstream API error: ${response.status}. Using fallback template.`)
			return {
				ok: true,
				html: generateFallbackHtml(shapes, context),
				source: 'fallback'
			}
		}

		const data = (await response.json()) as any
		let rawHtml = data.choices?.[0]?.message?.content?.trim() || ''

		// Clean markdown wrappers if present
		rawHtml = rawHtml.replace(/^```html\s*/i, '').replace(/```\s*$/i, '').trim()

		if (rawHtml.includes('<html') || rawHtml.includes('<!DOCTYPE html>')) {
			return {
				ok: true,
				html: rawHtml,
				source: 'llm'
			}
		}

		return {
			ok: true,
			html: generateFallbackHtml(shapes, context),
			source: 'fallback'
		}
	} catch (err: any) {
		clearTimeout(timeout)
		console.warn(`[Make Real] Exception during LLM generation: ${err?.message || err}. Using fallback template.`)
		return {
			ok: true,
			html: generateFallbackHtml(shapes, context),
			source: 'fallback'
		}
	}
}
